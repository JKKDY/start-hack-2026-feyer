"""Generate python/differometor_native/components.py from upstream components.py.

Usage: python tools/generate_components.py <upstream components.py> <output path>

Constants, DEFAULT_PROPERTIES and PARAMETER_BOUNDS are copied verbatim.
NumPy-only helpers are copied verbatim. Detector readouts delegate to the
native extension. JAX component kernels become stubs with the identical
signature that raise NotImplementedError until the native kernels exist.
"""

import ast
import sys

COPY_VERBATIM = {"laser_np", "directional_beamsplitter_matrix", "nothing_matrix"}
NATIVE = {"amplitude_detector", "power_detector", "signal_detector"}
# Pure-array helpers: copied with jax.numpy -> numpy (same formulas, same order).
COPY_WITH_NUMPY = {
    "standardize_output", "incidence_angle_left", "incidence_angle_right", "phase_shift",
    "reflectivity_left", "reflectivity_right", "transmissivity", "optomechanical_phase_left",
    "optomechanical_phase_right", "tuning_correction", "mirror_matrix", "beamsplitter_matrix",
}

HEADER = '''"""
Optical component definitions (native Differometor, API-compatible).

GENERATED by tools/generate_components.py from upstream
differometor/components.py. Do not edit by hand; regenerate instead.

- Constants, DEFAULT_PROPERTIES and PARAMETER_BOUNDS are identical to upstream.
- The 19 registered kernels (FUNCTIONS) run in the native extension, with
  upstream signatures; they return complex128 NumPy arrays of length 4.
- Helper formulas (incidence angles, phase shifts, reflectivities, mirror and
  beamsplitter matrices, ...) are upstream code with jax.numpy -> numpy.
- Detector readouts run in the native extension.
See docs/api-compatibility.md and docs/kernels.md.
"""

from __future__ import annotations

import numpy as np

from differometor_native._native import detectors as _detectors
from differometor_native._native import kernels as _kernels


def _native_kernel(index: int, parameters) -> np.ndarray:
    """Evaluate registered kernel `index` natively on a real parameter vector.

    Upstream evaluates kernels on complex128 parameters whose imaginary parts
    are zero; complex input is accepted only when it is real-valued.
    """
    array = np.asarray(parameters)
    if np.iscomplexobj(array):
        if np.any(array.imag != 0):
            raise ValueError("native component kernels take real parameters (imaginary parts must be 0).")
        array = array.real
    return _kernels.evaluate(index, np.ascontiguousarray(array, dtype=np.float64).reshape(-1))

'''

NATIVE_SOURCE = '''

def amplitude_detector(solution):
    """sqrt(0.5 * EPSILON_0C) * |solution|, elementwise (native kernel)."""
    array = np.ascontiguousarray(solution, dtype=np.complex128)
    return _detectors.amplitude_detector(array)


def power_detector(solution):
    """0.5 * EPSILON_0C * |solution|**2, elementwise (native kernel)."""
    array = np.ascontiguousarray(solution, dtype=np.complex128)
    return _detectors.power_detector(array)


def signal_detector(carrier, signal):
    """conj(carrier) * signal[:N] + carrier * signal[N:2N] with N = carrier.shape[0].

    2-D inputs with column broadcasting, and 1-D inputs, run natively. Any other
    shape combination uses the NumPy expression, so upstream's broadcasting
    semantics are kept exactly.
    """
    carrier = np.asarray(carrier)
    signal = np.asarray(signal)
    n = carrier.shape[0]
    if carrier.ndim == 1 and signal.ndim == 1 and signal.shape[0] >= 2 * n:
        out = _detectors.signal_detector_2d(
            np.ascontiguousarray(carrier.reshape(n, 1), dtype=np.complex128),
            np.ascontiguousarray(signal.reshape(-1, 1), dtype=np.complex128),
        )
        return out.reshape(n)
    if (
        carrier.ndim == 2
        and signal.ndim == 2
        and signal.shape[0] >= 2 * n
        and (carrier.shape[1] == 1 or signal.shape[1] == 1 or carrier.shape[1] == signal.shape[1])
    ):
        return _detectors.signal_detector_2d(
            np.ascontiguousarray(carrier, dtype=np.complex128),
            np.ascontiguousarray(signal, dtype=np.complex128),
        )
    upper_sideband = np.conj(carrier) * signal[:n]
    lower_sideband = carrier * signal[n : n * 2]
    return upper_sideband + lower_sideband
'''


def main(src_path: str, out_path: str) -> None:
    src = open(src_path, encoding="utf-8").read()
    tree = ast.parse(src)
    functions_node = [n for n in tree.body if isinstance(n, ast.Assign) and
                      isinstance(n.targets[0], ast.Name) and n.targets[0].id == "FUNCTIONS"][0]
    registered = {elt.id: i for i, elt in enumerate(functions_node.value.elts)}
    parts = [HEADER]
    stub_names = []
    for node in tree.body:
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            names = [t.id for t in targets if isinstance(t, ast.Name)]
            if names and names[0] == "FUNCTIONS":
                continue
            if names and names[0].isupper():
                parts.append(ast.get_source_segment(src, node) + "\n")
        elif isinstance(node, ast.FunctionDef):
            if node.name in registered:
                signature = ast.unparse(node.args).replace("jnp.ndarray", "np.ndarray")
                doc = ast.get_docstring(node)
                first = doc.strip().splitlines()[0] if doc else node.name
                index = registered[node.name]
                parts.append(
                    f"\n\ndef {node.name}({signature}) -> np.ndarray:\n"
                    f'    """{first} (native kernel, FUNCTIONS[{index}])."""\n'
                    f"    return _native_kernel({index}, parameters)\n"
                )
                stub_names.append(node.name)
            elif node.name in COPY_WITH_NUMPY:
                segment = ast.get_source_segment(src, node)
                segment = segment.replace("jnp.ndarray", "np.ndarray").replace("jnp.", "np.")
                parts.append("\n\n" + segment + "\n")
            elif node.name in COPY_VERBATIM:
                parts.append("\n\n" + ast.get_source_segment(src, node) + "\n")
            elif node.name in NATIVE:
                continue
            else:
                raise SystemExit(f"upstream function {node.name!r} is not classified; update the generator")
    parts.append(NATIVE_SOURCE)
    # FUNCTIONS keeps upstream order and length so integer indices stay valid.
    functions = [n for n in tree.body if isinstance(n, ast.Assign) and
                 isinstance(n.targets[0], ast.Name) and n.targets[0].id == "FUNCTIONS"][0]
    parts.append("\n\n" + ast.get_source_segment(src, functions) + "\n")
    open(out_path, "w", encoding="utf-8", newline="\n").write("".join(parts))
    print(f"wrote {out_path}: {len(stub_names)} native kernel wrappers")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
