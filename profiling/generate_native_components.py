"""Lower the fixed-width component formulas and pullbacks to C++ at build time."""
from pathlib import Path
import sys

import jax
import jax.numpy as jnp
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from differometor.components import FUNCTIONS


def literal(x):
    x = complex(x)
    return f"C({x.real!r}, {x.imag!r})"


def lower(program, name):
    """Scalarize the small, at-most-one-dimensional component jaxprs."""
    graph = program.jaxpr
    lines = []
    values = {}

    def read(var):
        if hasattr(var, "val"):
            return [literal(x) for x in np.asarray(var.val).flat]
        return values[var]

    for index, var in enumerate(graph.invars):
        prefix = ("x", "g")[index]
        values[var] = [f"{prefix}[{i}]" for i in range(var.aval.size)]
    for var, constant in zip(graph.constvars, program.consts, strict=True):
        values[var] = [literal(x) for x in np.asarray(constant).flat]

    for index, eq in enumerate(graph.eqns):
        op, kw = eq.primitive.name, eq.params
        args = [read(var) for var in eq.invars]
        size = eq.outvars[0].aval.size
        if op == "split":
            offset = 0
            for var, count in zip(eq.outvars, kw["sizes"], strict=True):
                values[var] = args[0][offset:offset + count]
                offset += count
            continue
        if op == "slice":
            result = args[0][kw["start_indices"][0]:kw["limit_indices"][0]]
            assert kw["strides"] in (None, (1,))
        elif op in ("squeeze", "convert_element_type"):
            result = args[0]
        elif op == "broadcast_in_dim":
            result = args[0] * (size // len(args[0]))
        elif op == "concatenate":
            result = sum(args, [])
        elif op == "pad":
            left, right, stride = kw["padding_config"][0]
            assert stride == 0
            result = args[1] * left + args[0] + args[1] * right
        else:
            vectors = [a * size if len(a) == 1 else a for a in args]
            binary = {"add": "+", "add_any": "+", "sub": "-", "mul": "*", "div": "/"}
            if op in binary:
                result = [f"{a} {binary[op]} {b}" for a, b in zip(*vectors, strict=True)]
            elif op == "reduce_sum":
                result = [" + ".join(args[0])]
            elif op == "integer_pow":
                n = kw["y"]
                result = [f"ipow({a}, {n})" for a in vectors[0]]
            elif op in {"neg", "square", "rsqrt"}:
                forms = {"neg": "-{0}", "square": "{0} * {0}", "rsqrt": "C(1) / std::sqrt({0})"}
                result = [forms[op].format(a) for a in vectors[0]]
            elif op in {"asin", "conj", "cos", "cosh", "exp", "log", "sin", "sinh", "sqrt"}:
                # JAX's real-valued intermediates retain their real math semantics.
                real = eq.invars[0].aval.dtype.kind != "c"
                result = [f"std::{op}({a}{'.real()' if real else ''})" for a in vectors[0]]
            else:
                raise ValueError(f"Unsupported component operation: {op}")
            variables = [f"v{index}_{i}" for i in range(size)]
            lines.extend(f"    const C {v} = {expr};" for v, expr in zip(variables, result, strict=True))
            result = variables
        assert len(result) == size
        values[eq.outvars[0]] = result

    lines.extend(f"    out[{i}] = {v};" for i, v in enumerate(read(graph.outvars[0])))
    return f"static void {name}(const C* x, const C* g, C* out) {{\n" + "\n".join(lines) + "\n}\n"


def main():
    jax.config.update("jax_enable_x64", True)
    x, g = [jax.ShapeDtypeStruct((n,), jnp.complex128) for n in (7, 4)]
    contents = ["// Generated by profiling/generate_native_components.py."]
    for index, component in enumerate(FUNCTIONS):
        def pullback(inputs, seed):
            return jax.vjp(component, inputs)[1](seed)[0]

        contents.append(lower(jax.make_jaxpr(component)(x), f"component_{index}"))
        contents.append(lower(jax.make_jaxpr(pullback)(x, g), f"pullback_{index}"))
    for name in ("component", "pullback"):
        functions = ", ".join(f"{name}_{index}" for index in range(len(FUNCTIONS)))
        contents.append(f"static const Kernel {name}s[] = {{{functions}}};")
    (ROOT / "differometor" / "_native_components.inc").write_text("\n".join(contents) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
